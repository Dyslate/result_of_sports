let current = 'fr';

/** 'auto' → browser language (fr if it starts with "fr", otherwise en). */
export function resolveLang(setting) {
  if (setting === 'fr' || setting === 'en') return setting;
  // chrome.i18n follows Chrome's UI language everywhere, including the service worker.
  let ui = '';
  try {
    ui = globalThis.chrome?.i18n?.getUILanguage?.() ?? '';
  } catch {
    /* outside the extension */
  }
  const nav = (ui || globalThis.navigator?.language || 'fr').toLowerCase();
  return nav.startsWith('fr') ? 'fr' : 'en';
}

export function setLang(setting) {
  current = resolveLang(setting);
  if (globalThis.document) document.documentElement.lang = current;
  return current;
}

export const lang = () => current;
export const locale = () => (current === 'fr' ? 'fr-FR' : 'en-GB');

export function t(key, vars) {
  let s = DICT[current][key] ?? DICT.fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Localised name of an object shaped { name, en }. */
export const localName = (o) => (current === 'en' && o?.en ? o.en : o?.name ?? '');

/** Translates static markup: data-i18n, data-i18n-html, -title, -placeholder, -aria. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-html]').forEach((el) => (el.innerHTML = t(el.dataset.i18nHtml)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  if (globalThis.document) document.title = t('app.title');
}
